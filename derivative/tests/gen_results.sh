#!/bin/bash
# Regenerates TEST_RESULTS.md by actually running every tier. Numbers in that
# file are therefore always from the latest real run.
set -u
OUT=TEST_RESULTS.md
TMP=$(mktemp -d /tmp/deriv_results.XXXX)
trap 'rm -rf "$TMP"' EXIT

golden_line=$(./run_tests.sh 2>&1 | grep '^Results:' || echo 'RESULTS NOT PRODUCED')
golden_exit=$?
error_line=$(./run_error_tests.sh 2>&1 | grep '^Results:' || echo 'RESULTS NOT PRODUCED')
if command -v python3 >/dev/null 2>&1; then
    oracle_line=$(python3 tests/oracle_check.py 200 2>&1 | grep '^oracle:' || echo 'oracle: NO SUMMARY LINE')
else
    oracle_line="oracle: SKIPPED (python3 not installed)"
fi
cov_out=$(./tests/coverage.sh 2>&1)
cov_line=$(printf '%s\n' "$cov_out" | grep 'line coverage' || echo 'coverage: NOT MEASURED')
gate_line=$(printf '%s\n' "$cov_out" | grep -E '^Coverage gate' || echo 'gate: UNKNOWN')

cat > "$OUT" <<EOF
# Derivative Calculator — Test Results

**This file is generated by \`make results\` — do not edit by hand.**
Last regeneration: $(date -u +%Y-%m-%dT%H:%M:%SZ)

| Tier | Command | Result |
|---|---|---|
| Golden suite (exact match) | ./run_tests.sh | $golden_line |
| Error paths + empty stdin + demo mode | ./run_error_tests.sh | $error_line |
| Random sympy-oracle battery (seed 42) | python3 tests/oracle_check.py 200 | $oracle_line |
| gcov line coverage of expr.y | ./tests/coverage.sh | $cov_line ($gate_line) |

Run \`make test-all\` to execute all tiers, \`make results\` to rewrite this file.

## Untested by design (known limits, see DEEP_ANALYSIS_REPORT.md)

- Silent int overflow for inputs > INT_MAX (finding H4) — asserting current
  behavior would pin a bug.
- Super-exponential cost on very long product chains (finding H5).
- Memory leaks from the intentional free_expr() no-op (findings R1/R2).

## History

- The original harness never compared output and claimed a bogus 91/91.
- 2026-09-01 rebaseline: expectations regenerated only after sympy-verified
  every program output (7 original expectations were mathematically wrong).
- 2026-09-01 test-suite expansion found and fixed two real bugs:
  collect_terms() freed a live term list on zero-coefficient merge (segfault
  on e.g. '0*x+5'), and negate_terms() negated only the first term of a list
  (wrong result for '--x').
EOF
echo "TEST_RESULTS.md regenerated."
